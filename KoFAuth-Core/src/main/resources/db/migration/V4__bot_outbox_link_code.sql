-- =============================================================================
--  KoFAuth V4 — недостающие значения перечислений
-- =============================================================================
--
--  Обе правки чинят один и тот же класс отказа: код на Java знает значение,
--  которого нет в колонке ENUM. MySQL в строгом режиме отвергает такую вставку
--  целиком (ошибка 1265), а в нестрогом молча записывает пустую строку — и
--  чтение возвращает не то значение, которое записывали.
--
--  1. bot_outbox.kind ← LINK_CODE
--
--     Команда /discord с включённым `link.post-code-to-channel` кладёт в
--     очередь сообщение вида LINK_CODE (см. BotMessage.Kind и LinkCommand).
--     В V3 этого значения в колонке не было, поэтому публикация кода в
--     служебный канал не работала ни разу с момента её появления: вставка
--     отвергалась, игрок видел только код в игре, а в журнале оставалось
--     «Код привязки не опубликован в канал Discord».
--
--  2. login_history.source ← SYSTEM
--
--     EventSource.SYSTEM существует с самого начала (AuthContext.system()), и
--     хотя сегодня попытки входа с таким источником не записываются, колонка
--     обязана принимать все значения перечисления: иначе первый же вызов из
--     системного контекста отвергнет строку истории входов — ровно там, где
--     терять её нельзя.
--
--  Значения добавляются В КОНЕЦ списка. Это существенно: MySQL хранит ENUM
--  номером позиции, и вставка нового значения в середину переписала бы смысл
--  уже записанных строк. Добавление в конец не трогает существующие данные и
--  выполняется без копирования таблицы.
-- =============================================================================

ALTER TABLE bot_outbox
    MODIFY COLUMN kind ENUM ('LOGIN_APPROVAL', 'LOGIN_APPROVAL_RESOLVED',
                             'LOGIN_NOTICE', 'SECURITY_NOTICE',
                             'LINK_CODE') NOT NULL;

ALTER TABLE login_history
    MODIFY COLUMN source ENUM ('MINECRAFT', 'WEB', 'TELEGRAM', 'DISCORD', 'API',
                               'SYSTEM') NOT NULL DEFAULT 'MINECRAFT';
