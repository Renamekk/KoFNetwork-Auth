"""Настройки оформления карточек.

Отдельный модуль, потому что его читают настройки ботов, а те загружаются
раньше всего остального. Здесь нет ни одной зависимости — ни от PIL, ни от
ресурсов, — поэтому чтение окружения не может упасть из-за того, что
библиотека рисования не установлена или каталог со шрифтами пуст.

Ни одно из значений не влияет на поведение бота: при любых из них он
работает, просто выглядит богаче или беднее.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class CardSettings:
    """Что и как рисовать.

    :param enabled: выключатель на случай, когда карточки мешают: слабая
        машина, отладка текстовых экранов, узкий канал у игроков
    :param directory: каталог ресурсов; пусто — встроенный в пакет
    :param quality: качество JPEG. На плоской тёмной панели разницы между 84 и
        90 не видно даже вплотную, а картинка легче почти на треть; ниже 78
        начинает сыпаться иллюстрация под логотипом
    :param workers: сколько карточек рисуется одновременно. Больше двух не
        нужно: рисование должно уступать процессор подтверждению входа,
        а не соревноваться с ним
    :param cache_entries: сколько готовых картинок помнить
    :param cache_bytes: сколько памяти им отдать
    :param cache_ttl: сколько секунд картинка считается свежей. Данные на ней
        устаревают молча — никто не сообщит боту, что игрок зашёл в игру
    """

    enabled: bool = True
    directory: str = ""
    quality: int = 84
    workers: int = 2
    cache_entries: int = 48
    cache_bytes: int = 24 * 1024 * 1024
    cache_ttl: float = 600.0
