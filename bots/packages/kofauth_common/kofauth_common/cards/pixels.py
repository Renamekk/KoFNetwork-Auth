"""Пиксельные значки карточек.

Значки описаны сеткой из символов, а не картинками. Причин три.

1. **Стиль.** Карточка подражает Minecraft: значок обязан быть набран
   квадратами по сетке, а не сглаженной векторной иконкой. Сетка гарантирует
   это по построению — нарисовать здесь плавную кривую попросту нечем.
2. **Размер.** Двенадцать картинок в трёх размерах — это два десятка файлов,
   которые нужно хранить, версионировать и не забыть положить в образ.
   Сетка занимает столько же места, сколько её изображение в этом файле.
3. **Проверяемость.** Сетку читает тест: он видит, что значок непустой,
   квадратный и не съехал за границы, — а по PNG это узнать нечем.

Масштаб выбирается при отрисовке: каждая клетка становится квадратом целого
размера, поэтому пиксель остаётся пикселем при любом кегле.
"""

from __future__ import annotations

from typing import Final

#: Сторона сетки. Все значки одного размера: разнокалиберные значки в столбце
#: слева от строк выглядят как случайно собранные, даже если каждый по
#: отдельности хорош.
GRID: Final = 9

Glyph = tuple[str, ...]


def _check(name: str, rows: Glyph) -> Glyph:
    """Сверяет форму сетки при загрузке модуля.

    Опечатка в одной строке сдвинула бы весь рисунок, и заметить это на глаз
    на карточке 900 пикселей шириной практически нельзя.
    """
    if len(rows) != GRID or any(len(row) != GRID for row in rows):
        raise ValueError(f"Значок {name!r}: ожидалась сетка {GRID}×{GRID}")
    return rows


#: Профиль: голова и плечи.
PERSON: Final = _check("person", (
    "...###...",
    "..#####..",
    "..#####..",
    "...###...",
    ".........",
    "..#####..",
    ".#######.",
    "#########",
    "#########",
))

#: Регистрация: отрывной календарь.
CALENDAR: Final = _check("calendar", (
    "..#...#..",
    "#########",
    "#########",
    "#########",
    "#.......#",
    "#.##.##.#",
    "#.......#",
    "#.##.##.#",
    "#########",
))

#: Последний вход: часы со стрелками.
CLOCK: Final = _check("clock", (
    "..#####..",
    ".#.....#.",
    "#...#...#",
    "#...#...#",
    "#...####.",
    "#.......#",
    "#.......#",
    ".#.....#.",
    "..#####..",
))

#: Защита: щит.
SHIELD: Final = _check("shield", (
    "#########",
    "#.......#",
    "#.......#",
    "#.......#",
    ".#.....#.",
    ".#.....#.",
    "..#...#..",
    "...#.#...",
    "....#....",
))

#: Уведомления: колокол.
BELL: Final = _check("bell", (
    "...###...",
    "..#####..",
    "..#####..",
    ".#######.",
    ".#######.",
    "#########",
    "#########",
    ".........",
    "...###...",
))

#: Второй фактор: закрытый замок.
LOCK: Final = _check("lock", (
    "..#####..",
    ".#.....#.",
    ".#.....#.",
    "#########",
    "#########",
    "###...###",
    "####.####",
    "####.####",
    "#########",
))

#: Команды: ключ.
KEY: Final = _check("key", (
    "..###....",
    ".#...#...",
    ".#...#...",
    "..###....",
    "...#.....",
    "...#.....",
    "...####..",
    "...#.....",
    "...###...",
))

#: Привязка: два звена цепи.
LINK: Final = _check("link", (
    ".###.....",
    "#...#....",
    "#...#....",
    "#...#....",
    ".###.###.",
    "....#...#",
    "....#...#",
    "....#...#",
    ".....###.",
))

#: Сессии: монитор на подставке.
SCREEN: Final = _check("screen", (
    "#########",
    "#.......#",
    "#.......#",
    "#.......#",
    "#.......#",
    "#########",
    "...###...",
    "...###...",
    ".#######.",
))

#: Внимание: треугольник с восклицательным знаком.
WARNING: Final = _check("warning", (
    "....#....",
    "...#.#...",
    "...#.#...",
    "..#.#.#..",
    "..#.#.#..",
    ".#..#..#.",
    ".#.....#.",
    "#...#...#",
    "#########",
))

#: Успешный вход.
CHECK: Final = _check("check", (
    ".........",
    ".......##",
    "......##.",
    ".....##..",
    "#...##...",
    "##.##....",
    ".####....",
    "..##.....",
    ".........",
))

#: Неудачный вход.
CROSS: Final = _check("cross", (
    ".........",
    ".##...##.",
    "..##.##..",
    "...###...",
    "....#....",
    "...###...",
    "..##.##..",
    ".##...##.",
    ".........",
))

#: Игрок в сети.
PLAYER: Final = _check("player", (
    ".#######.",
    "#.##.##.#",
    "#.......#",
    "#.#####.#",
    ".#######.",
    "..#####..",
    ".##...##.",
    ".#.....#.",
    ".##...##.",
))

ICONS: Final[dict[str, Glyph]] = {
    "person": PERSON,
    "calendar": CALENDAR,
    "clock": CLOCK,
    "shield": SHIELD,
    "bell": BELL,
    "lock": LOCK,
    "key": KEY,
    "link": LINK,
    "screen": SCREEN,
    "warning": WARNING,
    "check": CHECK,
    "cross": CROSS,
    "player": PLAYER,
}

#: Украшение по бокам заголовка: ромб из четырёх квадратов, как в макете.
ORNAMENT: Final = (
    ".#.",
    "###",
    ".#.",
)


def glyph(name: str) -> Glyph | None:
    """Сетка значка либо ``None``, если такого нет.

    Отсутствие значка не должно ронять карточку: строка нарисуется без
    плитки, и данные человек всё равно увидит.
    """
    return ICONS.get(name)
