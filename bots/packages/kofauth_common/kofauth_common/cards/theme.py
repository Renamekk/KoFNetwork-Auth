"""Палитра и разметка карточек KoF Network.

Числа собраны в одном месте не ради удобства, а ради одинаковости: карточку
рисуют два бота и один сборщик статических экранов, и три копии одних и тех же
отступов разъехались бы на первой же правке.

Геометрия
---------

Холст 900×1125 — та же пропорция 4:5, что и у макетов (1122×1402), только в
размере, который телефон показывает без потерь, а мессенджер отправляет за
доли секунды. Верхняя половина — готовая иллюстрация из шаблона: логотип,
сакура, персонаж. Нижняя — панель с данными, которую рисует бот.

Панель одна и та же на всех динамических экранах и по положению совпадает с
той, что уже вырезана из шаблона. Разные рамки на разных экранах читались бы
как разные приложения, а вырезать под каждый экран свой шаблон значило бы
хранить пять фонов вместо одного.

Цвета
-----

Палитра сети — чёрное, белое и красный ``#FF2D2D``. Зелёный здесь один и
появляется ровно в одном значении — «включено» на экране защиты. Это не
украшение: «ВКЛ» и «ВЫКЛ» отличаются одним слогом, и на беглом взгляде их
разводит только цвет. Везде, где состояния нет, зелёного нет тоже.
"""

from __future__ import annotations

from typing import Final

# --------------------------------------------------------------------- холст

#: Ширина и высота карточки. 4:5 — самый высокий формат, который Telegram и
#: Discord показывают в ленте целиком, не пряча низ под «нажмите, чтобы
#: развернуть».
WIDTH: Final = 900
HEIGHT: Final = 1125

#: Панель с данными. Совпадает с вырезом в шаблоне: шаблон готовится тем же
#: модулем, поэтому расхождение невозможно по построению.
PANEL_LEFT: Final = 56
PANEL_TOP: Final = 500
PANEL_RIGHT: Final = 844
PANEL_BOTTOM: Final = 1084
PANEL_RADIUS: Final = 28

#: Насколько вырез в шаблоне шире панели. Свечение рамки уходит наружу, и без
#: запаса под ним осталась бы кромка старой панели с чужим текстом.
PANEL_BLEED: Final = 18

#: Внутренние поля панели.
PAD_X: Final = 30
PAD_TOP: Final = 26
PAD_BOTTOM: Final = 24

#: Заголовок: центр строки и разделитель под ним — от верха панели.
TITLE_CENTER: Final = 100
TITLE_DIVIDER: Final = 152

#: Отступ содержимого от верха панели. Начинается сразу под разделителем.
CONTENT_TOP: Final = 176

#: Плитка со значком слева от строки и промежуток до текста.
TILE_SIZE: Final = 62
TILE_RADIUS: Final = 12
TILE_GAP: Final = 22

#: Высота строки: подбирается под число строк, но не выходит за эти пределы.
#: Нижняя граница — предел читаемости на телефоне, верхняя — чтобы три строки
#: не расползлись по всей панели.
ROW_MIN: Final = 46
ROW_MAX: Final = 104

#: Предел высоты строки списка. Он выше, чем у полей: у строки истории бывает
#: приписка второй строкой, и в высоту поля она не влезает.
ENTRY_MAX: Final = 110

# --------------------------------------------------------------------- цвета

#: Фирменный красный сети.
RED: Final = (255, 45, 45)
RED_DIM: Final = (196, 32, 34)
RED_DARK: Final = (86, 16, 20)

#: Фон панели — тёплый почти-чёрный, а не чистый: чистый чёрный на фоне
#: иллюстрации читается как дыра, а не как стекло поверх неё.
PANEL_FILL: Final = (14, 12, 13)
PANEL_ALPHA: Final = 236

#: Подложка плитки со значком.
TILE_FILL: Final = (30, 16, 18)
TILE_ALPHA: Final = 226

#: Подложка строки истории — чуть светлее панели, чтобы строки читались
#: списком, а не сплошным полотном.
ENTRY_FILL: Final = (24, 16, 18)
ENTRY_ALPHA: Final = 150

#: Текст. Кремовый вместо чистого белого: белый рядом с красным даёт
#: неприятный контраст, кремовый — тот же, что в логотипе сети.
CREAM: Final = (247, 240, 228)
TEXT: Final = (238, 232, 224)
MUTED: Final = (150, 140, 136)

#: Единственный зелёный — «включено». См. пояснение в заголовке модуля.
GREEN: Final = (53, 209, 72)

#: Предупреждение. Появляется только там, где состояние действительно требует
#: внимания: временная блокировка, неудачный вход.
AMBER: Final = (255, 176, 32)

#: Тон текста. Имя описывает роль, а не цвет: карточку читают и глазами, и
#: тестами, и «accent» переживёт смену оттенка, а «red» — нет.
TONE_TEXT: Final = "text"
TONE_ACCENT: Final = "accent"
TONE_TITLE: Final = "title"
TONE_MUTED: Final = "muted"
TONE_OK: Final = "ok"
TONE_WARN: Final = "warn"
TONE_DANGER: Final = "danger"

TONES: Final[dict[str, tuple[int, int, int]]] = {
    TONE_TEXT: TEXT,
    TONE_ACCENT: RED,
    TONE_TITLE: CREAM,
    TONE_MUTED: MUTED,
    TONE_OK: GREEN,
    TONE_WARN: AMBER,
    TONE_DANGER: RED,
}


def colour(tone: str) -> tuple[int, int, int]:
    """Цвет тона. Неизвестный тон — обычный текст, а не исключение.

    Карточка не должна падать из-за опечатки в названии тона: пропавшая строка
    на экране профиля хуже, чем строка не того оттенка.
    """
    return TONES.get(tone, TEXT)


# ------------------------------------------------------------------- размеры

#: Кегли. Заголовок крупный, значения — размером с подпись к кнопке: карточку
#: смотрят с телефона в руке, а не с монитора.
SIZE_TITLE: Final = 46
SIZE_ROW: Final = 30
SIZE_ROW_SMALL: Final = 24
SIZE_ENTRY: Final = 26
SIZE_SUB: Final = 20
SIZE_FOOTER: Final = 22
SIZE_SECTION: Final = 30
SIZE_LINE: Final = 25

#: Ряд кеглей, по которому текст ужимается, если не влез. Ниже последнего
#: значения текст не уменьшается — вместо этого он обрезается многоточием:
#: нечитаемая строка ничем не лучше отсутствующей.
SHRINK: Final = (1.0, 0.92, 0.84, 0.76, 0.68)

#: Версия оформления. Входит в отпечаток содержимого, поэтому правка палитры
#: или разметки сама по себе обесценивает кэш — иначе после обновления бота
#: люди ещё десять минут видели бы карточки, нарисованные прежним кодом.
LAYOUT_VERSION: Final = "1"
