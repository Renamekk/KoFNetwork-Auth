"""Графические экраны ботов KoF Network.

Гибридный интерфейс: картинка показывает состояние, кнопки под ней остаются
родными кнопками мессенджера. Картинка не заменяет ни навигацию, ни
подтверждение входа — она заменяет только чтение четырёх строк текста подряд.

Что чем рисуется
----------------

* **Главное меню и справка** — заранее подготовленные картинки с диска.
  Данных игрока на них нет, а значит, и собирать их на каждый запрос незачем.
* **Профиль, защита, история и сессии** — собираются из ответа ``/api/bot``
  в момент показа и живут в памяти ограниченное время.

Чего здесь нет
--------------

* **Порождающих моделей.** Иллюстрация нарисована заранее и лежит в ресурсах;
  во время работы бот только пишет по ней текст. Запрос к чему бы то ни было
  внешнему ради экрана профиля — это и задержка, и зависимость от чужой
  доступности там, где её быть не должно.
* **Файлов на пользователя.** Готовые картинки лежат в кэше в памяти, с
  пределами по числу, объёму и сроку. Каталог с персональными картинками
  пришлось бы чистить, переносить и объяснять — а он всё равно хранил бы
  личные данные дольше, чем нужно.
* **Обязательности.** Любой отказ — нет библиотеки рисования, нет шрифта, нет
  шаблона, не отправилось — означает текстовый экран, а не отсутствие экрана.
  Поэтому здесь не импортируется ничего тяжёлого: PIL и ресурсы подгружаются
  при первой картинке, а не при запуске бота.
"""

