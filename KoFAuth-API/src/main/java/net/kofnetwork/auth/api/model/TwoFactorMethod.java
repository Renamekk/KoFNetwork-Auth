package net.kofnetwork.auth.api.model;

/**
 * Второй фактор аутентификации. На аккаунте может быть включено несколько одновременно —
 * в базе это колонка типа {@code SET}.
 *
 * <p>Когда включено больше одного метода, игроку предлагается тот, что выше по
 * {@link #priority()}: подтверждение нажатием в Telegram занимает секунду, ввод кода
 * из приложения — заметно дольше, а письмо может идти минуты.
 */
public enum TwoFactorMethod {

    /** Google Authenticator и совместимые: шестизначный код из приложения. */
    TOTP(20),

    /** Кнопка «Подтвердить» в личном чате Telegram-бота. */
    TELEGRAM(30),

    /** Кнопка в личных сообщениях Discord-бота. */
    DISCORD(25),

    /** Код в письме. Самый медленный и наименее надёжный — только как запасной вариант. */
    EMAIL(10);

    private final int priority;

    TwoFactorMethod(int priority) {
        this.priority = priority;
    }

    /** Чем выше значение, тем предпочтительнее метод при наличии выбора. */
    public int priority() {
        return priority;
    }

    /**
     * Требует ли метод активного канала связи с внешней службой.
     *
     * <p>{@link #TOTP} проверяется целиком внутри процесса, поэтому работает и при
     * недоступности Telegram, Discord или SMTP. Остальные методы при отказе внешней
     * службы должны уступать место запасному, иначе игрок окажется заперт.
     */
    public boolean requiresExternalDelivery() {
        return this != TOTP;
    }
}
