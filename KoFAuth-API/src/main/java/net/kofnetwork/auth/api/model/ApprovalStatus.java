package net.kofnetwork.auth.api.model;

/**
 * Состояние подтверждения входа.
 *
 * <p>Переход из {@link #PENDING} происходит ровно один раз и одной атомарной операцией.
 * Именно поэтому состояний четыре, а не два: «истекло» и «отклонено» приводят к разным
 * сообщениям игроку и к разным записям в аудите, а «повторное нажатие» обязано быть
 * отличимо от «нажатие принято» — иначе вторая кнопка молча создавала бы вторую сессию.
 */
public enum ApprovalStatus {

    /** Кнопка показана, решения ещё нет. */
    PENDING,

    /** Владелец нажал «Войти». */
    APPROVED,

    /** Владелец нажал «Отклонить». */
    DENIED,

    /** Никто не нажал вовремя. */
    EXPIRED;

    public boolean isFinal() {
        return this != PENDING;
    }
}
