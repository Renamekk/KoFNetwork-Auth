package net.kofnetwork.auth.api.model;

/**
 * Способ предъявления CAPTCHA. Соответствует {@code captcha.type}.
 *
 * <p>Все варианты решают одну задачу — отличить человека от автоматики — но отличаются
 * стойкостью и удобством. Тип задаётся конфигурацией и может быть повышен динамически:
 * при всплеске подозрительной активности {@code CaptchaService} переключается на более
 * стойкий вариант, не требуя перезагрузки.
 */
public enum CaptchaType {

    /**
     * Выбрать в GUI предмет, названный в сообщении.
     * Устойчив к OCR, но уязвим к простому боту, читающему пакеты содержимого инвентаря.
     */
    BLOCK_SELECT(1),

    /**
     * Ввести в чат показанный текст.
     * Самый слабый вариант: текст передаётся клиенту как обычная строка.
     */
    TEXT_INPUT(1),

    /** Нажать нужную кнопку из нескольких. Эквивалентен угадыванию с шансом 1/N. */
    BUTTON_CLICK(1),

    /**
     * Сетка GUI: найти ячейку, удовлетворяющую условию, среди отвлекающих.
     * Вариант по умолчанию: разумный баланс стойкости и скорости прохождения.
     */
    GUI_GRID(2),

    /**
     * Код, отрисованный на карте с шумом и искажениями.
     * Самый стойкий: требует от бота распознавания изображения. Дороже остальных
     * по трафику (карта — это 16 КБ пикселей), поэтому включается точечно.
     */
    MAP_IMAGE(3);

    private final int strength;

    CaptchaType(int strength) {
        this.strength = strength;
    }

    /** Условная стойкость, 1..3. Используется при автоматическом повышении сложности. */
    public int strength() {
        return strength;
    }

    /** Требует ли тип открытия инвентаря (а не только чата). */
    public boolean requiresInventory() {
        return this == BLOCK_SELECT || this == GUI_GRID || this == BUTTON_CLICK;
    }
}
