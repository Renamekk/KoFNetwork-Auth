package net.kofnetwork.auth.api.exception;

/**
 * Хранилище состояния недоступно.
 *
 * <p><b>Почему это исключение, а не «нет данных».</b> Прежний контракт кэша объявлял
 * промах и отказ одним событием: обе ситуации отвечали пустым значением, и вызывающий
 * шёл в MySQL. Для кэша это верно — но в Redis лежит не только кэш. Там живут состояние
 * машины входа, привязка UUID к сессии, счётчики ограничения скорости и межпроцессная
 * синхронизация; ни у чего из этого нет копии в MySQL, из которой можно было бы
 * восстановиться.
 *
 * <p>Поэтому «Redis не отвечает» превращалось в «игрок не аутентифицирован, лимитов нет,
 * события не доходят» — и система продолжала обслуживать вход так, будто всё в порядке.
 * Это худший вид отказа: снаружи он выглядит как исправная работа.
 *
 * <p>Операции, для которых различие существенно, вызывают
 * {@code CacheProvider.critical()} и получают этот отказ явно. Дальше он поднимается до
 * вызывающего, который обязан отказать в действии, а не выполнить его вслепую.
 */
public class CacheUnavailableException extends KoFAuthException {

    public CacheUnavailableException(String message) {
        super(message);
    }

    public CacheUnavailableException(String message, Throwable cause) {
        super(message, cause);
    }
}
