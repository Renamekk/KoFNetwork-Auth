package net.kofnetwork.auth.api.model;

/**
 * Состояние аккаунта. Соответствует колонке {@code users.status}.
 *
 * <p>Не путать с временной блокировкой после серии неудачных попыток входа: она
 * выражается полем {@code lockedUntil} и снимается сама. {@link #LOCKED} же ставится
 * администратором и снимается только командой {@code /auth unlock}.
 */
public enum AccountStatus {

    /** Обычное состояние: вход разрешён. */
    ACTIVE,

    /**
     * Заблокирован администратором ({@code /auth lock}) либо автоматикой после
     * подтверждённой попытки взлома. Вход запрещён, сессии разорваны.
     */
    LOCKED,

    /** Забанен. Отличается от {@link #LOCKED} тем, что не подразумевает разблокировки. */
    BANNED,

    /**
     * Запрошено удаление. Аккаунт не пускает в игру, но данные ещё хранятся —
     * период на отмену операции владельцем.
     */
    PENDING_DELETION;

    /** Может ли аккаунт в этом состоянии пройти аутентификацию. */
    public boolean allowsLogin() {
        return this == ACTIVE;
    }
}
