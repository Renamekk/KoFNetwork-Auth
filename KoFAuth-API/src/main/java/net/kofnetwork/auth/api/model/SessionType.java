package net.kofnetwork.auth.api.model;

/** Канал, в котором была создана сессия. Соответствует {@code sessions.type}. */
public enum SessionType {

    /** Игровая сессия на Minecraft-сервере. */
    GAME,

    /** Сессия личного кабинета. */
    WEB,

    /** Сессия Telegram-бота. */
    TELEGRAM,

    /** Сессия Discord-бота. */
    DISCORD,

    /** Машинный доступ по API-ключу. */
    API;

    /**
     * Нужно ли жёстко привязывать сессию к IP-адресу.
     *
     * <p>Для игры это оправданно: адрес меняется редко, а угон сессии стоит дорого.
     * Для веба — вредно: мобильный клиент теряет сессию при каждом переключении
     * между Wi-Fi и сотовой сетью, и пользователи начинают жаловаться, а не радоваться
     * безопасности. Там защита строится на коротком access-токене и ротации refresh.
     */
    public boolean bindsToIpByDefault() {
        return this == GAME;
    }
}
