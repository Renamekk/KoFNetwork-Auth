package net.kofnetwork.auth.api.config;

import org.jetbrains.annotations.NotNull;

import java.util.concurrent.CompletableFuture;

/**
 * Компонент, который нужно пересобрать при перезагрузке конфигурации.
 *
 * <p>Большинству компонентов этот интерфейс не нужен: они читают значения через
 * {@link ConfigurationService} при каждом обращении и подхватывают изменения сами.
 * Реализуют его лишь те, кто держит ресурс, привязанный к настройкам, — пул соединений
 * Hikari, подключение к Redis, транспорт SMTP. Такой ресурс надо закрыть и создать заново.
 */
public interface Reloadable {

    /**
     * Применяет новую конфигурацию.
     *
     * <p><b>Требование к реализации:</b> при неудаче старый ресурс должен остаться
     * рабочим. Порядок — «создать новый, проверить, подменить, закрыть старый», а не
     * «закрыть старый, создать новый»: опечатка в пароле базы при втором порядке
     * оставит сеть без аутентификации до перезапуска.
     *
     * @return future, завершающийся после применения; исключение означает, что
     *         перезагрузка не удалась и продолжает работать прежняя конфигурация
     */
    @NotNull CompletableFuture<Void> reload();

    /** Имя компонента для сообщения о результате {@code /auth reload}. */
    default @NotNull String componentName() {
        return getClass().getSimpleName();
    }

    /**
     * Порядок перезагрузки: меньшее значение раньше.
     *
     * <p>Существенно, потому что зависимости выстроены снизу вверх: репозитории
     * бесполезно пересоздавать раньше пула соединений, на котором они работают.
     */
    default int reloadOrder() {
        return 100;
    }
}
