package net.kofnetwork.auth.api.event;

import org.jetbrains.annotations.NotNull;

import java.time.Instant;

/**
 * Базовый тип доменного события.
 *
 * <p>События — механизм развязки. Успешный вход интересует пять независимых подсистем
 * (аудит, уведомления в Telegram, уведомления в Discord, метрики, инвалидация кэша), и
 * прямые вызовы из {@code AuthenticationService} в каждую из них превратили бы его в
 * узел, который нужно править при добавлении любой новой реакции.
 *
 * <p><b>Распространение.</b> События, у которых {@link #isDistributed()} возвращает
 * {@code true}, помимо локальной шины уходят в Redis Pub/Sub и доставляются всем узлам
 * сети. Смена пароля на сайте должна разорвать игровую сессию на прокси, а прокси и
 * веб-API — разные процессы.
 */
public interface AuthEvent {

    /** Момент возникновения события. */
    @NotNull Instant occurredAt();

    /**
     * Идентификатор аккаунта, которого касается событие.
     * {@code null} для событий, не связанных с конкретным аккаунтом.
     */
    @org.jetbrains.annotations.Nullable Long accountId();

    /**
     * Нужно ли доставлять событие на другие узлы сети.
     *
     * <p>По умолчанию {@code true}. Переопределяется в {@code false} для событий, чья
     * реакция целиком локальна, — рассылать их по сети значит платить сериализацией
     * и трафиком без единого потребителя на удалённой стороне.
     */
    default boolean isDistributed() {
        return true;
    }
}
